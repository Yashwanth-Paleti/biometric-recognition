"""
Biometric Threshold Calibration and Evaluation Script.

Stage 3 Empirical Calibration:
Evaluates genuine and impostor Euclidean (L2) distance distributions
generated by InsightFace Buffalo_L (512-dimensional normalized embeddings).
Computes FAR (False Accept Rate), FRR (False Reject Rate), Accuracy,
EER (Equal Error Rate), and confusion matrix across candidate thresholds.
"""

from collections import defaultdict
from itertools import combinations
import json
import sys
from pathlib import Path
import numpy as np

BASE_DIR = Path(__file__).resolve().parent.parent
if str(BASE_DIR) not in sys.path:
    sys.path.insert(0, str(BASE_DIR))

from app.biometric.face_engine import FaceEngine
from app.config.settings import settings
from app.utils.logging import logger



def discover_subjects() -> dict[str, list[Path]]:
    """Discovers available face images categorized by subject identity."""
    subjects = defaultdict(list)

    # 1. Dataset directory
    dataset_dir = BASE_DIR / "dataset"
    if dataset_dir.is_dir():
        for img in dataset_dir.glob("*.jpg"):
            stem = img.stem  # e.g. "1_Malhar", "4_Umang"
            name = stem.split("_", 1)[-1].upper() if "_" in stem else stem.upper()
            subjects[name].append(img)

    # 2. Test data directory
    test_data_dir = BASE_DIR / "test_data"
    if test_data_dir.is_dir():
        for img in test_data_dir.glob("*.jpg"):
            stem = img.stem
            if stem.startswith("yashwanth"):
                subjects["YASHWANTH"].append(img)
            elif stem == "unknown":
                subjects["UNKNOWN"].append(img)
            else:
                subjects[stem.upper()].append(img)

    # 3. Legacy directory (Umang multi-image series)
    legacy_umang = BASE_DIR / "legacy" / "4_Umang"
    if legacy_umang.is_dir():
        for img in legacy_umang.glob("*.jpg"):
            subjects["UMANG"].append(img)

    return dict(subjects)


def extract_subject_embeddings(engine: FaceEngine, subjects: dict[str, list[Path]]) -> dict[str, list[dict]]:
    """Extracts 512-d normalized embeddings for all discovered subject images."""
    extracted = defaultdict(list)
    logger.info("Extracting embeddings for calibration dataset...")

    for subject, paths in sorted(subjects.items()):
        for path in paths:
            try:
                rgb = engine.process_image(str(path))
                faces = engine.detect_faces(rgb)
                if len(faces) == 0:
                    logger.warning(f"No face detected in {path.name}, skipping.")
                    continue
                embedding = engine.generate_embedding(faces[0])
                extracted[subject].append({
                    "path": str(path.relative_to(BASE_DIR)),
                    "filename": path.name,
                    "embedding": embedding,
                })
            except Exception as e:
                logger.warning(f"Error processing {path.name}: {e}")

    return dict(extracted)


def compute_pairwise_distances(subject_embeddings: dict[str, list[dict]]) -> tuple[list[dict], list[dict]]:
    """
    Computes all pairwise Euclidean (L2) distances partitioned into
    genuine comparisons (same subject) and impostor comparisons (different subjects).
    """
    genuine_pairs = []
    impostor_pairs = []

    all_items = []
    for subject, items in subject_embeddings.items():
        for item in items:
            all_items.append((subject, item))

    # All unique combinations of 2 images
    for (subj_a, item_a), (subj_b, item_b) in combinations(all_items, 2):
        vec_a = item_a["embedding"]
        vec_b = item_b["embedding"]

        # Euclidean distance
        l2_dist = float(np.linalg.norm(vec_a - vec_b))
        # Cosine similarity for normalized vectors: sim = 1 - (dist^2) / 2
        cos_sim = float(np.clip(1.0 - (l2_dist ** 2) / 2.0, -1.0, 1.0))

        record = {
            "subject_a": subj_a,
            "file_a": item_a["filename"],
            "subject_b": subj_b,
            "file_b": item_b["filename"],
            "l2_distance": l2_dist,
            "cosine_similarity": cos_sim,
        }

        if subj_a == subj_b:
            genuine_pairs.append(record)
        else:
            impostor_pairs.append(record)

    return genuine_pairs, impostor_pairs


def evaluate_thresholds(
    genuine_pairs: list[dict],
    impostor_pairs: list[dict],
    thresholds: list[float],
) -> list[dict]:
    """Calculates FAR, FRR, accuracy, and confusion matrix for candidate thresholds."""
    results = []
    num_genuine = len(genuine_pairs)
    num_impostor = len(impostor_pairs)

    gen_dists = np.array([p["l2_distance"] for p in genuine_pairs]) if num_genuine > 0 else np.array([])
    imp_dists = np.array([p["l2_distance"] for p in impostor_pairs]) if num_impostor > 0 else np.array([])

    for t in thresholds:
        # Match decision: distance <= threshold
        ta = int(np.sum(gen_dists <= t)) if num_genuine > 0 else 0  # True Accept
        fr = int(np.sum(gen_dists > t)) if num_genuine > 0 else 0   # False Reject
        tr = int(np.sum(imp_dists > t)) if num_impostor > 0 else 0  # True Reject
        fa = int(np.sum(imp_dists <= t)) if num_impostor > 0 else 0 # False Accept

        far = fa / num_impostor if num_impostor > 0 else 0.0
        frr = fr / num_genuine if num_genuine > 0 else 0.0
        accuracy = (ta + tr) / (num_genuine + num_impostor) if (num_genuine + num_impostor) > 0 else 0.0

        results.append({
            "threshold": round(t, 3),
            "ta": ta,
            "fr": fr,
            "tr": tr,
            "fa": fa,
            "far": round(far, 4),
            "frr": round(frr, 4),
            "accuracy": round(accuracy, 4),
            "abs_diff_far_frr": round(abs(far - frr), 4),
        })

    return results


def run_calibration() -> dict:
    """Executes full empirical biometric calibration analysis."""
    print("=" * 78)
    print("      CLOUD-BASED BIOMETRIC AUTHENTICATION SYSTEM — STAGE 3 CALIBRATION")
    print("=" * 78)

    engine = FaceEngine()
    engine.initialize()

    subjects = discover_subjects()
    print(f"\n[1] Discovered {len(subjects)} subjects across dataset/, test_data/, and legacy/:")
    for s, p in sorted(subjects.items()):
        print(f"    - {s:12s}: {len(p)} image(s) ({', '.join(x.name for x in p)})")

    subject_embeddings = extract_subject_embeddings(engine, subjects)
    total_embeddings = sum(len(v) for v in subject_embeddings.values())
    print(f"\n[2] Extracted {total_embeddings} 512-dimensional embeddings.")

    genuine_pairs, impostor_pairs = compute_pairwise_distances(subject_embeddings)
    print(f"\n[3] Formed pairwise comparisons:")
    print(f"    - Genuine Comparisons  (same subject):      {len(genuine_pairs)}")
    print(f"    - Impostor Comparisons (different subjects): {len(impostor_pairs)}")

    gen_dists = [p["l2_distance"] for p in genuine_pairs]
    imp_dists = [p["l2_distance"] for p in impostor_pairs]

    gen_mean, gen_std = float(np.mean(gen_dists)), float(np.std(gen_dists))
    gen_min, gen_max = float(np.min(gen_dists)), float(np.max(gen_dists))
    imp_mean, imp_std = float(np.mean(imp_dists)), float(np.std(imp_dists))
    imp_min, imp_max = float(np.min(imp_dists)), float(np.max(imp_dists))

    print("\n[4] Empirical Distance Distributions (Euclidean L2):")
    print(f"    - Genuine Distances:  Mean = {gen_mean:.4f}, Std = {gen_std:.4f}, Min = {gen_min:.4f}, Max = {gen_max:.4f}")
    print(f"    - Impostor Distances: Mean = {imp_mean:.4f}, Std = {imp_std:.4f}, Min = {imp_min:.4f}, Max = {imp_max:.4f}")

    # Evaluate candidate thresholds from 0.50 to 1.30 in steps of 0.05
    candidate_thresholds = [round(x, 2) for x in np.arange(0.50, 1.35, 0.05)]
    # Ensure current configured threshold is tested
    if settings.biometric_match_threshold not in candidate_thresholds:
        candidate_thresholds.append(settings.biometric_match_threshold)
    candidate_thresholds = sorted(list(set(candidate_thresholds)))

    evaluation_table = evaluate_thresholds(genuine_pairs, impostor_pairs, candidate_thresholds)

    print("\n[5] Threshold Evaluation Sweep:")
    print(f"    {'Threshold':<10} | {'FAR (%)':<10} | {'FRR (%)':<10} | {'Accuracy (%)':<12} | {'Confusion Matrix (TA/FR/TR/FA)'}")
    print("    " + "-" * 72)
    for r in evaluation_table:
        is_current = " <-- CURRENT DEFAULT" if abs(r["threshold"] - settings.biometric_match_threshold) < 1e-3 else ""
        print(
            f"    {r['threshold']:<10.2f} | {r['far']*100:<10.2f} | {r['frr']*100:<10.2f} | "
            f"{r['accuracy']*100:<12.2f} | TA={r['ta']}, FR={r['fr']}, TR={r['tr']}, FA={r['fa']}{is_current}"
        )

    # Find Equal Error Rate (EER) candidate
    best_eer_cand = min(evaluation_table, key=lambda x: x["abs_diff_far_frr"])

    # Current settings evaluation
    curr_t = settings.biometric_match_threshold
    curr_eval = next((r for r in evaluation_table if abs(r["threshold"] - curr_t) < 1e-3), None)

    print("\n[6] Calibration Summary & Recommendations:")
    print(f"    - Current Threshold:  {curr_t:.2f}")
    if curr_eval:
        print(f"      * FAR at {curr_t:.2f}: {curr_eval['far']*100:.2f}% (FA={curr_eval['fa']}/{len(impostor_pairs)})")
        print(f"      * FRR at {curr_t:.2f}: {curr_eval['frr']*100:.2f}% (FR={curr_eval['fr']}/{len(genuine_pairs)})")
        print(f"      * Overall Accuracy:  {curr_eval['accuracy']*100:.2f}%")
    print(f"    - Approximate EER Threshold: {best_eer_cand['threshold']:.2f} (FAR={best_eer_cand['far']*100:.2f}%, FRR={best_eer_cand['frr']*100:.2f}%)")

    summary_data = {
        "dataset": "Facial-Recognition-Attendance-System local and legacy dataset",
        "total_subjects": len(subjects),
        "total_images": total_embeddings,
        "genuine_comparisons": len(genuine_pairs),
        "impostor_comparisons": len(impostor_pairs),
        "current_threshold": curr_t,
        "current_far": curr_eval["far"] if curr_eval else None,
        "current_frr": curr_eval["frr"] if curr_eval else None,
        "current_accuracy": curr_eval["accuracy"] if curr_eval else None,
        "eer_threshold": best_eer_cand["threshold"],
        "eer_far": best_eer_cand["far"],
        "eer_frr": best_eer_cand["frr"],
        "genuine_stats": {
            "mean": gen_mean, "std": gen_std, "min": gen_min, "max": gen_max
        },
        "impostor_stats": {
            "mean": imp_mean, "std": imp_std, "min": imp_min, "max": imp_max
        },
        "evaluation_sweep": evaluation_table,
    }

    return summary_data


if __name__ == "__main__":
    run_calibration()
